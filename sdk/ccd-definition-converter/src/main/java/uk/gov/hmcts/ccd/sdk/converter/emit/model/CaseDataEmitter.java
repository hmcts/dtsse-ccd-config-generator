package uk.gov.hmcts.ccd.sdk.converter.emit.model;

import com.palantir.javapoet.AnnotationSpec;
import com.palantir.javapoet.ClassName;
import com.palantir.javapoet.FieldSpec;
import com.palantir.javapoet.JavaFile;
import com.palantir.javapoet.TypeSpec;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import javax.lang.model.element.Modifier;
import uk.gov.hmcts.ccd.sdk.converter.api.EmitContext;
import uk.gov.hmcts.ccd.sdk.converter.api.SourceEmitter;
import uk.gov.hmcts.ccd.sdk.converter.model.CaseTypeModel;
import uk.gov.hmcts.ccd.sdk.converter.model.ComplexTypeModel;
import uk.gov.hmcts.ccd.sdk.converter.model.FieldModel;

/**
 * Emits the generated {@code CaseData} class for a case type.
 *
 * <p>Each CaseField row in the model (except Label-type fields and overlay-tagged rows) becomes a
 * private field annotated with {@code @CCD} and optionally {@code @JsonProperty}.
 *
 * <p>When the model splits CaseData into {@code @JsonUnwrapped} sub-objects
 * ({@link CaseTypeModel#getCaseDataGroups()}), each group is emitted as its own plain class in the
 * model package, and CaseData declares an initialised {@code @JsonUnwrapped} member per group ahead
 * of its flat fields, ordered by member name, so the class opens with its outline.
 *
 * <p>Generated by ccd-definition-converter from CaseDataEmitter — do not edit by hand.
 */
public class CaseDataEmitter implements SourceEmitter {

  private static final ClassName JSON_NAMING =
      ClassName.get("com.fasterxml.jackson.databind.annotation", "JsonNaming");
  private static final ClassName NAMING_STRATEGIES =
      ClassName.get("com.fasterxml.jackson.databind", "PropertyNamingStrategies");
  private static final ClassName BUILDER_DEFAULT = ClassName.get("lombok", "Builder", "Default");

  @Override
  public List<JavaFile> emit(CaseTypeModel model, EmitContext context) {
    String pkg = context.modelPackage();
    final FieldEmitHelper helper = new FieldEmitHelper(pkg, context.accessPackage(),
        context.typeFqnOverrides());

    List<ComplexTypeModel> groups = model.getCaseDataGroups() == null
        ? List.of() : model.getCaseDataGroups();
    Map<String, ComplexTypeModel> groupsByClass = new LinkedHashMap<>();
    for (ComplexTypeModel group : groups) {
      groupsByClass.put(group.getJavaClassName(), group);
    }

    // Group containers first (by member name), then the flat fields in definition order.
    List<FieldModel> containers = new ArrayList<>();
    List<FieldModel> flat = new ArrayList<>();
    for (FieldModel field : model.getCaseFields()) {
      // Skip overlay-tagged fields (they go to passthrough)
      if (field.getOverlayTags() != null && !field.getOverlayTags().isEmpty()) {
        continue;
      }
      if (field.getUnwrapPrefix() != null && groupsByClass.containsKey(field.getJavaType())) {
        containers.add(field);
      } else {
        flat.add(field);
      }
    }
    containers.sort(Comparator.comparing(FieldModel::getJavaName));
    int fieldCount = containers.size() + flat.size();
    boolean builder = fieldCount > 0 && fieldCount <= LombokAnnotations.ALL_ARGS_FIELD_LIMIT;

    List<FieldSpec> fields = new ArrayList<>();
    Map<String, String> groupPrefixes = new LinkedHashMap<>();
    for (FieldModel container : containers) {
      groupPrefixes.put(container.getJavaType(), container.getUnwrapPrefix());
      // Initialised so a getter chain never meets null on a hand-built CaseData; Jackson creates
      // the group itself when it deserialises.
      FieldSpec.Builder spec = helper.buildField(container).toBuilder()
          .initializer("new $T()", ClassName.get(pkg, container.getJavaType()));
      if (builder) {
        spec.addAnnotation(BUILDER_DEFAULT);
      }
      fields.add(spec.build());
    }
    for (FieldModel field : flat) {
      // Label-type fields are emitted as real members (String with @CCD(typeOverride=Label)) so
      // their CaseField row, Searchable flag and AuthorisationCaseField access classes round-trip
      // like any other field, rather than being reconstructed only where a tab or event happens to
      // reference them.
      fields.add(helper.buildField(field));
    }

    TypeSpec.Builder classBuilder = TypeSpec.classBuilder("CaseData")
        .addModifiers(Modifier.PUBLIC)
        .addJavadoc(context.banner(model.getCaseTypeId(), "CaseField"));
    LombokAnnotations.applyDataClass(classBuilder, fields.size());
    classBuilder.addFields(fields);

    List<JavaFile> files = new ArrayList<>();
    files.add(JavaFile.builder(pkg, classBuilder.build())
        .skipJavaLangImports(true)
        .indent("    ")
        .build());

    for (ComplexTypeModel group : groups) {
      List<FieldSpec> members = new ArrayList<>();
      for (FieldModel member : group.getMembers()) {
        members.add(helper.buildField(member));
      }
      String prefix = groupPrefixes.get(group.getJavaClassName());
      boolean prefixed = prefix != null && !prefix.isEmpty();
      TypeSpec.Builder gb = TypeSpec.classBuilder(group.getJavaClassName())
          .addModifiers(Modifier.PUBLIC)
          .addJavadoc(context.banner(model.getCaseTypeId(), "CaseField") + "\n\n"
              + "<p>CaseData fields " + (prefixed
                  ? "{@code " + prefix + "*}, unwrapped with {@code prefix = \"" + prefix + "\"}: "
                      + "the CCD field ID is the prefix plus the capitalised member name."
                  : "grouped under {@code @JsonUnwrapped}; each member keeps its CCD field ID.")
              + "\n");
      if (prefixed) {
        // Jackson's @JsonUnwrapped(prefix) concatenates verbatim; the SDK capitalises the member.
        // Upper-camel naming makes Jackson produce the same flat key the SDK derives.
        gb.addAnnotation(AnnotationSpec.builder(JSON_NAMING)
            .addMember("value", "$T.UpperCamelCaseStrategy.class", NAMING_STRATEGIES)
            .build());
      }
      LombokAnnotations.applyDataClass(gb, members.size());
      gb.addFields(members);
      files.add(JavaFile.builder(pkg, gb.build())
          .skipJavaLangImports(true)
          .indent("    ")
          .build());
    }
    return files;
  }
}
